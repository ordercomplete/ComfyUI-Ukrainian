    if 'nodeCategories' not in uk_main:
        en_categories = en_main.get('nodeCategories', {})
        uk_categories = {}
        
        for key, value in en_categories.items():
            # Перекладаємо ключ та значення
            translated_key = NODE_CATEGORIES_TRANSLATIONS.get(key.lower(), key)
