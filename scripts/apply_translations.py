#!/usr/bin/env python3
"""
Скрипт для застосування перекладів до українських файлів локалізації.
Читає English JSON, застосовує переклади зі словника, записує Ukrainian JSON.
"""

import json
import sys
from pathlib import Path
from typing import Dict, Any


# Шляхи до файлів
EN_DIR = Path("temp/ComfyUI_frontend/src/locales/en")
UK_DIR = Path("locales/uk")


def load_json(path: Path) -> Dict[str, Any]:
    """Завантажує JSON файл."""
    with open(path, 'r', encoding='utf-8') as f:
        return json.load(f)


def save_json(path: Path, data: Dict[str, Any]) -> None:
    """Зберігає JSON файл."""
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write('\n')


def apply_translations(en_data: Dict, translations: Dict, uk_data: Dict = None) -> Dict:
    """
    Застосовує переклади до даних.
    translations: словник {повний.шлях.ключ: "переклад"}
    """
    if uk_data is None:
        uk_data = json.loads(json.dumps(en_data))  # глибока копія
    
    def set_by_path(data: Dict, path: str, value: str) -> bool:
        """Встановлює значення за шляхом 'section.subsection.key'."""
        keys = path.split('.')
        current = data
        for key in keys[:-1]:
            if key not in current or not isinstance(current[key], dict):
                return False
            current = current[key]
        if keys[-1] in current:
            current[keys[-1]] = value
            return True
        return False
    
    applied = 0
    failed = 0
    for path, translation in translations.items():
        if set_by_path(uk_data, path, translation):
            applied += 1
        else:
            failed += 1
            print(f"⚠️  Ключ не знайдено: {path}")
    
    print(f"✅ Застосовано: {applied} перекладів")
    if failed:
        print(f"⚠️  Не знайдено: {failed} ключів")
    
    return uk_data


def process_file(filename: str, translations: Dict) -> None:
    """Обробляє один файл локалізації."""
    en_file = EN_DIR / filename
    uk_file = UK_DIR / filename
    
    if not en_file.exists():
        print(f"❌ English файл не знайдено: {en_file}")
        return
    
    print(f"\n{'='*60}")
    print(f"🔄 Обробка: {filename}")
    print(f"{'='*60}")
    
    en_data = load_json(en_file)
    
    # Завантажуємо існуючий UK файл, якщо він є (зберігаємо попередні переклади)
    if uk_file.exists():
        uk_data = load_json(uk_file)
        print(f"📂 Завантажено існуючий файл: {uk_file}")
    else:
        uk_data = json.loads(json.dumps(en_data))  # глибока копія EN
        print(f"🆕 Створено новий файл з English шаблону")
    
    uk_data = apply_translations(en_data, translations, uk_data)
    save_json(uk_file, uk_data)
    
    print(f"💾 Збережено: {uk_file}")


